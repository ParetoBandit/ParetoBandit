def load_raw_embedding_cache(
    cache_path: Optional[Path] = None,
    *,
    expected_encoder: Optional[str] = None,
) -> Dict[str, np.ndarray]:
    """Load the pre-computed raw (pre-PCA) embedding cache from disk.

    The raw cache stores full-dimensional SentenceTransformer output
    vectors (e.g. 384-dim for ``all-MiniLM-L6-v2``).  These can be
    projected through any PCA truncation downstream, avoiding the
    expensive encoder pass.

    Args:
        cache_path: Path to the ``.npz`` file.  If ``None``, uses the
            default from ``bandit_gpt.config.RAW_EMBEDDINGS_CACHE_PATH``.
        expected_encoder: If provided, verify the cache was built with
            this encoder name (from the sidecar ``.meta.json``).

    Returns:
        Dict mapping ``sha256(prompt) -> np.ndarray`` raw embedding.
        Returns an empty dict if the cache file does not exist or
        metadata validation fails (with a warning logged).
    """
    if cache_path is None:
        from bandit_gpt.config import RAW_EMBEDDINGS_CACHE_PATH
        cache_path = RAW_EMBEDDINGS_CACHE_PATH

    cache_path = Path(cache_path)
    if not cache_path.exists():
        logger.warning(
            "Raw embedding cache not found: %s — will embed live. "
            "Generate with: python scripts/precompute_embeddings.py",
            cache_path,
        )
        return {}

    meta_path = cache_path.with_suffix("").with_suffix(".meta.json")
    if meta_path.exists():
        meta = json.loads(meta_path.read_text())
        if expected_encoder and meta.get("encoder") != expected_encoder:
            logger.warning(
                "Raw cache encoder mismatch: expected %s, got %s — ignoring cache.",
                expected_encoder,
                meta.get("encoder"),
            )
            return {}
        logger.info(
            "Loaded raw embedding cache: %d prompts, %d-dim vectors (encoder=%s)",
            meta.get("n_prompts", 0),
            meta.get("vector_dim", 0),
            meta.get("encoder", "?"),
        )
    else:
        logger.info("Loaded raw embedding cache (no metadata sidecar).")

    data = np.load(cache_path)
    return {k: data[k] for k in data.files}


def get_raw_embeddings_for_data(
    data: List[Dict[str, Any]],
    cache: Dict[str, np.ndarray],
) -> np.ndarray:
    """Look up raw sentence embeddings for a list of data dicts.

    Thin convenience wrapper around :func:`get_raw_embeddings_for_prompts`
    that extracts the ``"prompt"`` key from each dict.

    Args:
        data: List of dicts, each with a ``"prompt"`` key.
        cache: Pre-loaded raw cache from :func:`load_raw_embedding_cache`.

    Returns:
        ``np.ndarray`` of shape ``(len(data), embedding_dim)``.
    """
    return get_raw_embeddings_for_prompts(
        [d["prompt"] for d in data], cache,
    )


def get_raw_embeddings_for_prompts(
    prompts: List[str],
    cache: Dict[str, np.ndarray],
) -> np.ndarray:
    """Look up raw embeddings for a list of prompts, returning an aligned matrix.

    Args:
        prompts: Ordered list of prompt strings.
        cache: Pre-loaded raw cache from :func:`load_raw_embedding_cache`.

    Returns:
        ``np.ndarray`` of shape ``(len(prompts), embedding_dim)`` with
        rows aligned to *prompts*.

    Raises:
        KeyError: If any prompt is missing from *cache*.  The error
            message lists up to 5 missing prompts to aid debugging.
    """
    missing: List[str] = []
    rows: List[np.ndarray] = []
    for prompt in prompts:
        key = _hash_prompt(prompt)
        vec = cache.get(key)
        if vec is None:
            missing.append(prompt)
        else:
            rows.append(vec)

    if missing:
        sample = missing[:5]
        preview = "; ".join(repr(p[:80]) for p in sample)
        raise KeyError(
            f"{len(missing)}/{len(prompts)} prompts missing from raw "
            f"embedding cache. First {min(len(missing), 5)}: {preview}. "
            f"Regenerate with: python scripts/precompute_embeddings.py"
        )

    return np.vstack(rows)


def project_embeddings(
    raw_emb: np.ndarray,
    pca: Any,
) -> List[np.ndarray]:
    """Project raw embeddings through PCA + whitening + bias (batch).

    Canonical batch version of ``bandit_gpt.calibration.embed_prompt``.
    All experiment scripts should use this single implementation to
    guarantee coordinate-system consistency with warmup priors.

    The whitening step divides each PCA component by
    ``sqrt(explained_variance)`` when ``pca.whiten`` is ``False``,
    producing approximately unit-variance features.  This matches the
    production ``FeatureService`` convention.

    Args:
        raw_emb: ``(n_prompts, raw_dim)`` array of SentenceTransformer
            output vectors.
        pca: Fitted (possibly truncated) ``sklearn.decomposition.PCA``
            model.

    Returns:
        List of ``(pca.n_components_ + 1,)`` context vectors (PCA
        components followed by a ``1.0`` bias term).
    """
    projected = pca.transform(raw_emb)

    if not bool(getattr(pca, "whiten", False)):
        ev = getattr(pca, "explained_variance_", None)
        if ev is not None:
            scale = 1.0 / np.sqrt(
                np.maximum(np.asarray(ev, dtype=np.float64), 1e-12)
            )
            projected = projected * scale

    bias = np.ones((projected.shape[0], 1))
    with_bias = np.hstack([projected, bias])
    return [with_bias[i] for i in range(with_bias.shape[0])]
