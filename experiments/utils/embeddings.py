"""
Cached embedding utilities for experiments.

Provides functions to load pre-computed embedding caches and embed
experiment datasets using them, falling back to live encoding for any
prompts not found.  This avoids re-running the expensive
SentenceTransformer + PCA pipeline on every experiment invocation.

Two cache layers are available (both generated by
``scripts/precompute_embeddings.py``):

1. **Raw embedding cache** — full-dimensional SentenceTransformer
   output (e.g. 384-dim for ``all-MiniLM-L6-v2``).  Use when you need to
   apply a custom PCA truncation or analysis on pre-PCA vectors.

2. **PCA-projected cache** — whitened, bias-appended context vectors
   ready for LinUCB.  Used by most standard experiments.

Both are ``.npz`` archives mapping ``sha256(prompt) -> vector``.

Typical usage::

    # PCA-projected (most experiments)
    from utils.embeddings import load_embedding_cache, embed_dataset_cached
    cache = load_embedding_cache()
    embeddings = embed_dataset_cached(data, cache, encoder, pca)

    # Raw pre-PCA (ablations, plotting)
    from utils.embeddings import load_raw_embedding_cache, get_raw_embeddings_for_prompts
    raw_cache = load_raw_embedding_cache()
    raw_matrix = get_raw_embeddings_for_prompts(prompts, raw_cache)
"""

from __future__ import annotations

import hashlib
import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

logger = logging.getLogger(__name__)


def _hash_prompt(prompt: str) -> str:
    """Deterministic SHA-256 hex digest of a prompt string."""
    return hashlib.sha256(prompt.encode("utf-8")).hexdigest()


def load_embedding_cache(
    cache_path: Optional[Path] = None,
    *,
    expected_encoder: Optional[str] = None,
    expected_pca_components: Optional[int] = None,
) -> Dict[str, np.ndarray]:
    """Load a pre-computed embedding cache from disk.

    Args:
        cache_path: Path to the ``.npz`` file.  If ``None``, uses the
            default from ``bandit_gpt.config.EMBEDDINGS_CACHE_PATH``.
        expected_encoder: If provided, verify the cache was built with
            this encoder name (from the sidecar ``.meta.json``).
        expected_pca_components: If provided, verify PCA dimensionality.

    Returns:
        Dict mapping ``sha256(prompt) -> np.ndarray`` context vector.
        Returns an empty dict if the cache file does not exist or
        metadata validation fails (with a warning logged).
    """
    if cache_path is None:
        from bandit_gpt.config import EMBEDDINGS_CACHE_PATH
        cache_path = EMBEDDINGS_CACHE_PATH

    cache_path = Path(cache_path)
    if not cache_path.exists():
        logger.warning(
            "Embedding cache not found: %s — will embed live. "
            "Generate with: python scripts/precompute_embeddings.py",
            cache_path,
        )
        return {}

    meta_path = cache_path.with_suffix("").with_suffix(".meta.json")
    if meta_path.exists():
        meta = json.loads(meta_path.read_text())
        if expected_encoder and meta.get("encoder") != expected_encoder:
            logger.warning(
                "Cache encoder mismatch: expected %s, got %s — ignoring cache.",
                expected_encoder,
                meta.get("encoder"),
            )
            return {}
        if (
            expected_pca_components is not None
            and meta.get("n_components") != expected_pca_components
        ):
            logger.warning(
                "Cache PCA mismatch: expected %d components, got %s — "
                "ignoring cache.",
                expected_pca_components,
                meta.get("n_components"),
            )
            return {}
        logger.info(
            "Loaded embedding cache: %d prompts, %d-dim vectors "
            "(encoder=%s, pca=%d comp)",
            meta.get("n_prompts", 0),
            meta.get("vector_dim", 0),
            meta.get("encoder", "?"),
            meta.get("n_components", 0),
        )
    else:
        logger.info("Loaded embedding cache (no metadata sidecar).")

    data = np.load(cache_path)
    return {k: data[k] for k in data.files}


def embed_dataset_cached(
    data: List[Dict[str, Any]],
    cache: Dict[str, np.ndarray],
    encoder: Any,
    pca: Any,
) -> List[np.ndarray]:
    """Embed a dataset using the cache, with live fallback for misses.

    For each entry in *data*, looks up ``sha256(entry["prompt"])`` in
    *cache*.  On a cache miss, falls back to ``embed_prompt()`` from
    ``bandit_gpt.calibration``.

    Args:
        data: List of dicts, each with a ``"prompt"`` key.
        cache: Pre-loaded cache from :func:`load_embedding_cache`.
        encoder: ``SentenceTransformer`` instance (used only on misses).
        pca: Fitted PCA model (used only on misses).

    Returns:
        List of embedding vectors aligned with *data*.
    """
    from bandit_gpt.calibration import embed_prompt

    embeddings: List[np.ndarray] = []
    n_miss = 0
    for entry in data:
        key = _hash_prompt(entry["prompt"])
        vec = cache.get(key)
        if vec is not None:
            embeddings.append(vec)
        else:
            embeddings.append(embed_prompt(entry["prompt"], encoder, pca))
            n_miss += 1

    if n_miss > 0:
        logger.warning(
            "Embedding cache: %d/%d misses — fell back to live encoding.",
            n_miss,
            len(data),
        )
    else:
        logger.info("Embedding cache: %d/%d hits (no live encoding needed).", len(data), len(data))

    return embeddings


